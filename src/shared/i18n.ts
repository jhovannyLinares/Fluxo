export const messages = { es, en } as const
export type Language = keyof typeof messages

/** Etiqueta de cada idioma en su propio idioma (selector de preferencias). */
export const LANGUAGE_NAMES: Record<Language, string> = { es: 'Español', en: 'English' }

/** Locale de Intl para fechas y números. */
export const LOCALES: Record<Language, string> = { es: 'es-MX', en: 'en-US' }

export function translate(lang: Language, key: MessageKey, vars?: Record<string, string | number>): string {
  const text = messages[lang][key] ?? messages.es[key]
  return vars ? text.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m)) : text
}
